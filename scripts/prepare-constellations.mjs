/**
 * Build the about view's constellation figures from real star positions.
 *
 *   node scripts/prepare-constellations.mjs
 *
 * Fetches the standard constellation stick figures from d3-celestial (Olaf
 * Frohn, BSD-3-Clause) and writes `src/scene/about/constellations.generated.js`:
 * one figure for each number of milestones from 1 to 10, so the timeline takes
 * the shape of a real constellation with exactly as many stars as it has
 * entries. Not part of the build — the output is committed, and only needs
 * regenerating if the choice of figures below changes.
 *
 * No constellation's figure has a single star, so one milestone is drawn as
 * Polaris, the North Star, and labelled as a star rather than a constellation.
 */
import fs from 'node:fs/promises'
import path from 'node:path'

const SOURCE = 'https://raw.githubusercontent.com/ofrohn/d3-celestial/master/data'
const OUT = path.join(path.dirname(new URL(import.meta.url).pathname), '..', 'src', 'scene', 'about', 'constellations.generated.js')

/*
 * For each count, the most recognisable figure with exactly that many stars in
 * d3-celestial's lines: chosen by eye from every figure of that size.
 */
const CHOICES = {
  2: 'CMi', // Canis Minor — Procyon and Gomeisa
  3: 'Tri', // Triangulum
  4: 'Cru', // Crux, the Southern Cross
  5: 'Cas', // Cassiopeia, the W
  6: 'Lyr', // Lyra
  7: 'UMi', // Ursa Minor, the Little Dipper
  8: 'Aql', // Aquila
  9: 'Aur', // Auriga — Capella's pentagon. Leo's sickle crowded its labels on a phone
  10: 'Cap', // Capricornus. Cepheus has three stars 15 px apart; no label fits between
}

/** Polaris (α UMi): RA 2h 31m 49s, Dec +89° 15′ 51″ — in d3-celestial's degrees. */
const POLARIS = { name: 'Polaris', kind: 'star', stars: [[0, 0]], edges: [] }

const rad = (d) => (d * Math.PI) / 180

/**
 * Project a figure's stars onto a flat plane as they appear on the sky: a
 * gnomonic projection about the figure's centre, north up and east to the
 * left — the sky is seen from inside, so east is the mirror of a map's. Then
 * centred and scaled so its longer axis spans −1 to +1, keeping its shape.
 */
function project(points) {
  const v = points.map(([ra, dec]) => [Math.cos(rad(dec)) * Math.cos(rad(ra)), Math.cos(rad(dec)) * Math.sin(rad(ra)), Math.sin(rad(dec))])
  const c = v.reduce((a, p) => a.map((x, i) => x + p[i]), [0, 0, 0])
  const ra0 = Math.atan2(c[1], c[0])
  const dec0 = Math.atan2(c[2], Math.hypot(c[0], c[1]))
  const flat = points.map(([ra, dec]) => {
    const d = rad(ra) - ra0
    const cosc = Math.sin(dec0) * Math.sin(rad(dec)) + Math.cos(dec0) * Math.cos(rad(dec)) * Math.cos(d)
    const x = (Math.cos(rad(dec)) * Math.sin(d)) / cosc
    const y = (Math.cos(dec0) * Math.sin(rad(dec)) - Math.sin(dec0) * Math.cos(rad(dec)) * Math.cos(d)) / cosc
    return [-x, y]
  })
  const xs = flat.map((p) => p[0])
  const ys = flat.map((p) => p[1])
  const cx = (Math.min(...xs) + Math.max(...xs)) / 2
  const cy = (Math.min(...ys) + Math.max(...ys)) / 2
  const half = Math.max(Math.max(...xs) - Math.min(...xs), Math.max(...ys) - Math.min(...ys)) / 2
  return flat.map(([x, y]) => [+((x - cx) / half).toFixed(4), +((y - cy) / half).toFixed(4)])
}

const lines = await (await fetch(`${SOURCE}/constellations.lines.json`)).json()
const names = await (await fetch(`${SOURCE}/constellations.json`)).json()
const nameOf = Object.fromEntries(names.features.map((f) => [f.id, f.properties.name]))

const figures = { 1: POLARIS }
for (const [count, id] of Object.entries(CHOICES)) {
  const feature = lines.features.find((f) => f.id === id)
  const key = (p) => `${p[0].toFixed(4)},${p[1].toFixed(4)}`
  const index = new Map()
  const points = []
  const edges = new Set()
  for (const segment of feature.geometry.coordinates) {
    for (const p of segment) {
      if (!index.has(key(p))) {
        index.set(key(p), points.length)
        points.push(p)
      }
    }
    for (let i = 1; i < segment.length; i++) {
      const a = index.get(key(segment[i - 1]))
      const b = index.get(key(segment[i]))
      edges.add(`${Math.min(a, b)}-${Math.max(a, b)}`)
    }
  }
  if (points.length !== Number(count)) throw new Error(`${id} has ${points.length} stars, not ${count}`)
  figures[count] = {
    name: nameOf[id],
    kind: 'constellation',
    stars: project(points),
    edges: [...edges].map((e) => e.split('-').map(Number)),
  }
}

const body = Object.entries(figures)
  .map(([n, f]) => `  ${n}: ${JSON.stringify(f)},`)
  .join('\n')

await fs.writeFile(OUT, `/*
 * GENERATED by scripts/prepare-constellations.mjs — do not edit by hand.
 *
 * Real constellation figures, one for each number of stars from 1 to 10.
 * Star positions and the lines joining them are from d3-celestial,
 * https://github.com/ofrohn/d3-celestial — Copyright (c) 2015, Olaf Frohn.
 * All rights reserved. Used under the BSD-3-Clause licence.
 *
 * Positions are projected as seen on the sky (north up, east left) and scaled
 * so each figure's longer axis spans -1 to +1, y up. One star has no
 * constellation, so 1 is Polaris, the North Star.
 */
export const CONSTELLATIONS = {
${body}
}
`)
console.log('wrote', Object.keys(figures).length, 'figures to', path.relative(process.cwd(), OUT))
